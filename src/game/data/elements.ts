export function getElementConfig(id: ElementId): ElementConfig {
  return ALL_ELEMENTS[id];
}

export function isValidElementId(value: unknown): value is ElementId {
  return typeof value === 'string' && value in ALL_ELEMENTS;
}

export function getElementLevelDamageMultiplier(level: number): number {
  const clamped = Math.max(1, Math.min(5, Math.floor(level)));
  return 1 + (clamped - 1) * 0.12;
}
